export type ScanResult = 
  | 'PASS'
  | 'DEFECT_BARCODE'
  | 'DEFECT_WEIGHT'
  | 'DEFECT_SEAL'
  | 'NO_READ';

export type EventProcessingStatus = 
  | 'PROCESSED'
  | 'DUPLICATE'
  | 'REJECTED'
  | 'OUT_OF_SEQUENCE';

export interface IScanEvent {
  eventId: string;             // Unique event identifier (UUID)
  cartonId: string;            // Physical carton identifier / barcode
  lineId: string;              // Line ID (e.g., 'LINE-01')
  shiftId?: string;            // Shift ID (e.g., 'SHIFT-A')
  sourceTimestamp: string;     // ISO string generated by scanner trigger
  ingestedAt: string;          // ISO string generated on backend receipt
  scanResult: ScanResult;
  status: EventProcessingStatus;
  scannerId?: string;          // Physical hardware / station ID
  stationId?: string;          // Workstation ID (e.g., 'WS-104')
  sku?: string;                // Product SKU
  batchNumber?: string;        // Production lot / batch
  positionMeters?: number;     // Conveyor position in meters
  isSimulated: boolean;        // Strictly flags simulated vs. real events
  metadata?: Record<string, any>;
}

export interface IBrandMixItem {
  brand: string;
  sku: string;
  count: number;
  percentage: number;
  color: string;
}

export interface IHourlyProduction {
  hour: string; // e.g., "06:00", "07:00", "08:00"
  total: number;
  byBrand: Record<string, number>;
}

export interface IConveyorSnapshot {
  lineId: string;
  shiftId: string;
  isSimulated: boolean;
  scannerStatus: {
    connected: boolean;
    lastHeartbeat: string | null;
    deviceId: string;
    model: string;
    latencyMs: number;
  };
  metrics: {
    totalScannedShift: number;
    passCount: number;
    defectCount: number;
    passRatePercent: number;
    firstPassYieldPercent: number;
    fpyTargetPercent: number;
    targetShiftScans: number;
    cartonsPerMinute: number;
    exceptions: {
      defectBarcode: number;
      defectWeight: number;
      defectSeal: number;
      noRead: number;
    };
  };
  hourlyProduction: IHourlyProduction[];
  brandMix: IBrandMixItem[];
  recentEvents: IScanEvent[];
  latestEvent: IScanEvent | null;
  serverTimestamp: string;
}

export interface ISimulationConfig {
  enabled: boolean;
  speedCpm: number;           // Target cartons per minute (e.g. 20 - 60)
  defectRatePercent: number;  // Desired anomaly rate (e.g. 5%)
  lineId: string;
}

